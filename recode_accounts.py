def run():
    with app.app_context():
        accs_by_code = {a.code: a for a in Account.query.all()}

        # ── Гүйлгээний тоог тодорхойлох (зөрчилд winner сонгоход) ──
        dt = dict(db.session.query(JournalLine.debit_account_id,  func.count()).group_by(JournalLine.debit_account_id).all())
        kt = dict(db.session.query(JournalLine.credit_account_id, func.count()).group_by(JournalLine.credit_account_id).all())
        def txn_count(acc): return (dt.get(acc.id, 0) or 0) + (kt.get(acc.id, 0) or 0)

        # ── Алхам 1: Бүх дансыг TEMP_ кодтой болго (зөрчилдөхгүйн тулд) ──
        print('Алхам 1: бүх дансыг TEMP_ болгоно...')
        for a in Account.query.all():
            a.code = 'TEMP_' + a.code
        db.session.commit()
        accs_by_code = {a.code: a for a in Account.query.all()}

        # ── Алхам 2: REMAP-ийн дагуу шинэ код + нэр оноо ──
        print('Алхам 2: шинэ код ононо...')
        # Хэрэв нэг target рүү олон данс очих бол гүйлгээтэй нь ялна
        target_winners = {}  # new_code → acc_id
        for old_code, (new_code, new_name) in REMAP.items():
            temp_key = 'TEMP_' + old_code
            acc = accs_by_code.get(temp_key)
            if not acc or new_code == 'DEACT':
                continue
            cnt = txn_count(acc)
            if new_code not in target_winners or cnt > target_winners[new_code][1]:
                target_winners[new_code] = (acc.id, cnt, old_code, new_name)

        # Шинэ код оноо
        assigned = set()  # assigned new codes
        for new_code, (acc_id, cnt, old_code, new_name) in target_winners.items():
            acc = db.session.get(Account, acc_id)
            acc.code = new_code
            acc.name = new_name
            assigned.add(old_code)
            mark = '★' if cnt > 0 else ' '
            print(f'  {mark} TEMP_{old_code} → {new_code}  {new_name[:40]}  [{cnt} гүйлгээ]')
        db.session.commit()

        # ── Алхам 3: REMAP-д орсон боловч winner болоогүй дансуудыг зохицуул ──
        print('Алхам 3: ялалтгүй дансуудыг зохицуулна...')
        accs_by_code = {a.code: a for a in Account.query.all()}
        for old_code, (new_code, new_name) in REMAP.items():
            temp_key = 'TEMP_' + old_code
            acc = accs_by_code.get(temp_key)
            if not acc:
                continue
            cnt = txn_count(acc)
            if new_code == 'DEACT':
                acc.code = old_code   # restore original code
                acc.is_active = False
                print(f'  DEACT TEMP_{old_code} → {old_code} (деактивжсан)')
            else:
                # didn't win target code — give it a unique code
                fallback = 'OLD_' + old_code
                acc.code = fallback
                acc.is_active = (cnt > 0)
                print(f'  SKIP  TEMP_{old_code} → {fallback} (гүйлгээ={cnt})')
        db.session.commit()

        # ── Алхам 4: Огт REMAP-д ороогүй TEMP_ дансуудыг буцаа ──
        print('Алхам 4: mapping-д ороогүй дансуудыг буцаана...')
        for a in Account.query.filter(Account.code.startswith('TEMP_')).all():
            orig = a.code[5:]  # strip TEMP_
            a.code = orig
            print(f'  RESTORE TEMP_{orig} → {orig}')
        db.session.commit()

        # ── Алхам 5: Шинэ дансууд нэмэх ──
        print('Алхам 5: шинэ дансуудыг нэмэнэ...')
        existing = {a.code for a in Account.query.all()}
        for code, name, atype in NEW_ACCOUNTS:
            if code not in existing:
                db.session.add(Account(code=code, name=name, type=atype, is_active=True))
                print(f'  + {code}  {name}')
        db.session.commit()

        # ── Дүн ──
        total = Account.query.count()
        active = Account.query.filter_by(is_active=True).count()
        print(f'\nДууслаа! Нийт данс: {total}, идэвхтэй: {active}')

if __name__ == '__main__':
    run()
